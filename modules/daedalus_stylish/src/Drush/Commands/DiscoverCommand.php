<?php

declare(strict_types=1);

namespace Drupal\daedalus_stylish\Drush\Commands;

use Drupal\Core\Config\ConfigFactoryInterface;
use Drupal\Core\Entity\EntityTypeManagerInterface;
use Drupal\daedalus_stylish\PropertyGroupPluginManager;
use Drupal\daedalus_stylish_discover\ElementDiscovery;
use Drush\Commands\AutowireTrait;
use Symfony\Component\Console\Attribute\AsCommand;
use Symfony\Component\Console\Command\Command;
use Symfony\Component\Console\Input\InputArgument;
use Symfony\Component\Console\Input\InputInterface;
use Symfony\Component\Console\Input\InputOption;
use Symfony\Component\Console\Output\OutputInterface;
use Symfony\Component\DependencyInjection\Attribute\Autowire;

/**
 * Scaffolds style guide YAML for a block type from its rendered markup.
 *
 * The rendering half lives in the optional daedalus_stylish_discover sub-module
 * (field_sample_value dependency); this command turns one discovery run into
 * a MODULE.page_builder.block_type.BUNDLE.yml starting point for a developer
 * to label, trim, constrain, and commit next to the templates it describes.
 */
#[AsCommand(
  name: 'daedalus_stylish:discover',
  description: 'Scaffolds style guide YAML for a block type from the classes its rendered markup emits.',
)]
final class DiscoverCommand extends Command {

  use AutowireTrait;

  public function __construct(
    #[Autowire(service: 'entity_type.manager')]
    protected EntityTypeManagerInterface $entityTypeManager,
    #[Autowire(service: 'config.factory')]
    protected ConfigFactoryInterface $configFactory,
    #[Autowire(service: 'plugin.manager.daedalus_stylish_property_group')]
    protected PropertyGroupPluginManager $propertyGroups,
    // NULL when the optional daedalus_stylish_discover module is not enabled; the
    // class reference is safe because it is never loaded in that case.
    #[Autowire(service: 'daedalus_stylish_discover.element_discovery')]
    protected ?ElementDiscovery $elementDiscovery = NULL,
  ) {
    parent::__construct();
  }

  /**
   * {@inheritdoc}
   */
  protected function configure(): void {
    $this
      ->addArgument('block_type', InputArgument::REQUIRED, 'The block type (block_content bundle) machine name.')
      ->addOption('theme', NULL, InputOption::VALUE_REQUIRED, 'The theme to render in. Templates decide the classes, so discovery is per theme. Defaults to the site default theme.')
      ->addUsage('testimonial')
      ->addUsage('testimonial --theme=olivero');
  }

  /**
   * {@inheritdoc}
   */
  protected function execute(InputInterface $input, OutputInterface $output): int {
    if ($this->elementDiscovery === NULL) {
      $output->writeln('<error>daedalus_stylish:discover renders the block type with sample data through the optional daedalus_stylish_discover module. Enable it first: drush en daedalus_stylish_discover</error>');
      return self::FAILURE;
    }
    $bundle = (string) $input->getArgument('block_type');
    $storage = $this->entityTypeManager->getStorage('block_content_type');
    if ($storage->load($bundle) === NULL) {
      $available = implode(', ', array_keys($storage->loadMultiple())) ?: '(none)';
      $output->writeln("<error>Unknown block type '$bundle'. Available block types: $available</error>");
      return self::FAILURE;
    }
    $theme = (string) ($input->getOption('theme') ?: $this->configFactory->get('system.theme')->get('default'));
    // Always re-render: the developer running this is iterating on the
    // templates the cache cannot see changing.
    $tree = $this->elementDiscovery->discover($bundle, $theme, TRUE);
    $output->writeln($this->scaffold($bundle, $theme, $tree));
    return self::SUCCESS;
  }

  /**
   * Builds the commented YAML scaffold.
   *
   * Hand-assembled rather than Yaml::encode()d — the comments ARE the
   * product; this file is a starting point for a human.
   *
   * @param string $bundle
   *   The block type the scaffold is for.
   * @param string $theme
   *   The theme whose elements were discovered.
   * @param array $tree
   *   The discovered shell tree
   *   (\Drupal\daedalus_stylish_discover\ElementDiscovery::discover).
   */
  protected function scaffold(string $bundle, string $theme, array $tree): string {
    $lines = [
      "# Style guide scaffold for the '$bundle' block type, generated by",
      "# `drush daedalus_stylish:discover $bundle` from the markup it renders with sample",
      "# values in the '$theme' theme. The elements tree mirrors that markup's",
      "# nesting; contains slots mark where field markup mounts.",
      '#',
      '# To adopt it:',
      "# 1. Save as MYMODULE.page_builder.block_type.$bundle.yml at the root of the",
      "#    module providing the block type (or THEME.page_builder.block_type.$bundle.yml",
      '#    to layer over it) — next to the templates that own these classes.',
      '# 2. Give each part an editor-facing label and delete the parts that should',
      '#    not be stylable.',
      '# 3. Trim the property groups and add constraints (see daedalus_stylish.api.php).',
      'property_groups:',
      ...$this->groupLines('  '),
    ];
    if ($tree === []) {
      $lines[] = '# No sub-element classes were discovered in the rendered sample markup.';
    }
    else {
      $lines[] = 'elements:';
      $this->scaffoldElements($tree, '  ', $lines);
    }
    return implode("\n", $lines);
  }

  /**
   * Appends one discovered tree level's part scaffolds, recursing.
   */
  protected function scaffoldElements(array $tree, string $indent, array &$lines): void {
    foreach ($tree as $selector => $part) {
      $lines[] = "$indent'$selector':";
      $lines[] = "$indent  # TODO: label this part for editors, e.g. 'Quote text'.";
      $lines[] = "$indent  label: '" . substr($selector, 1) . "'";
      if (isset($part['contains'])) {
        if (is_array($part['contains'])) {
          $lines[] = "$indent  contains:";
          foreach ($part['contains'] as $token) {
            $lines[] = "$indent    - '$token'";
          }
        }
        else {
          $lines[] = "$indent  contains: '{$part['contains']}'";
        }
      }
      $lines[] = "$indent  property_groups:";
      array_push($lines, ...$this->groupLines("$indent    "));
      if (!empty($part['elements'])) {
        $lines[] = "$indent  elements:";
        $this->scaffoldElements($part['elements'], "$indent    ", $lines);
      }
    }
  }

  /**
   * Formats every curated property group as an unconstrained YAML line.
   *
   * The generated wide-tier groups are deliberately absent: the scaffold is
   * a starting point a developer trims, and the wide tier is accept-when-
   * typed vocabulary, not a widget surface — a guide opts one in by
   * declaring it explicitly. The pseudo-only groups are absent too: every
   * line lands on a real element, where the guide build refuses them.
   *
   * @return string[]
   *   One "GROUP: { }" line per group at the given indent.
   */
  protected function groupLines(string $indent): array {
    return array_map(
      static fn (string $id): string => "$indent$id: { }",
      array_keys(array_intersect_key($this->propertyGroups->getCuratedGroups(), $this->propertyGroups->getElementGroups())),
    );
  }

}
