<?php

declare(strict_types=1);

namespace Drupal\daedalus_edit\Controller;

use Drupal\Component\Datetime\TimeInterface;
use Drupal\Core\Cache\Cache;
use Drupal\Core\Entity\EntityInterface;
use Drupal\Core\Entity\RevisionableEntityBundleInterface;
use Drupal\Core\Entity\RevisionableInterface;
use Drupal\Core\Entity\RevisionLogInterface;
use Drupal\Core\Url;
use Drupal\Core\Messenger\MessengerTrait;
use Drupal\Core\Controller\ControllerBase;
use Drupal\Core\Routing\RedirectDestinationInterface;
use Symfony\Component\HttpFoundation\Cookie;
use Symfony\Component\HttpFoundation\Request;
use Drupal\daedalus_tempstore\EntityTempstoreRepository;
use Symfony\Component\HttpFoundation\RedirectResponse;
use Symfony\Component\DependencyInjection\ContainerInterface;

/**
 * Daedalus Edit tempstore controller.
 */
class Tempstore extends ControllerBase {

  use MessengerTrait;

  /**
   * Constructs a Tempstore controller.
   *
   * @param \Drupal\daedalus_tempstore\EntityTempstoreRepository $tempstoreRepository
   *   The entity tempstore repository.
   * @param \Drupal\Core\Routing\RedirectDestinationInterface $redirect_destination
   *   The redirect destination.
   * @param \Drupal\Component\Datetime\TimeInterface $time
   *   The time service.
   */
  public function __construct(
    protected EntityTempstoreRepository $tempstoreRepository,
    RedirectDestinationInterface $redirect_destination,
    protected TimeInterface $time,
  ) {
    // ControllerBase declares the property untyped; assign, do not redeclare.
    $this->redirectDestination = $redirect_destination;
  }

  /**
   * {@inheritdoc}
   */
  public static function create(ContainerInterface $container) {
    return new static(
      $container->get('daedalus_tempstore.entity_tempstore_repository'),
      $container->get('redirect.destination'),
      $container->get('datetime.time'),
    );
  }

  /**
   * Save tempstore entities.
   */
  public function save(Request $request) {
    $first_entity = $this->loopThroughEntities($request, function ($entity) {
      $tempstore_entity = $this->tempstoreRepository->get($entity);
      $this->applyTempstoreChanges($tempstore_entity, $entity);
      $this->prepareNewRevision($entity);
      $entity->save();
      $this->tempstoreRepository->delete($entity);
    });

    $destination = $this->getRedirectDestination();
    if ($first_entity && $this->shouldRecomputeDestination($request->query->get('destination'), $first_entity)) {
      // If the page title was changed, the autogenerated URL could be
      // different.
      $url = $first_entity->toUrl()->toString();
      $request->query->set('destination', $url);
      $destination->set($url);
    }
    $destination = $destination->get();
    $response = new RedirectResponse($destination);
    $response->headers->setCookie((new Cookie('navigationMode', 'none', 0, $destination, NULL, FALSE, FALSE)));
    return $response;
  }

  /**
   * Marks a revisionable entity's pending save as a new revision.
   *
   * A programmatic $entity->save() keeps writing the CURRENT revision, so
   * page builder saves of revisionable entities (nodes, block_content roots)
   * silently rewrote history. Mirror core's entity form behavior
   * (ContentEntityForm::getNewRevisionDefault): the bundle config entity
   * decides (node types' new_revision, block_content types' revision), and a
   * bundle that cannot answer defaults to no new revision. Revision metadata
   * is stamped fresh so the revision log attributes the save to the editor,
   * not to the author of the revision it grew from.
   *
   * @param \Drupal\Core\Entity\EntityInterface $entity
   *   The entity about to be saved.
   */
  private function prepareNewRevision(EntityInterface $entity): void {
    if (!$entity instanceof RevisionableInterface || !$entity->getEntityType()->isRevisionable()) {
      return;
    }
    $bundle_entity_type = $entity->getEntityType()->getBundleEntityType();
    $bundle_entity = $bundle_entity_type
      ? $this->entityTypeManager()->getStorage($bundle_entity_type)->load($entity->bundle())
      : NULL;
    if (!$bundle_entity instanceof RevisionableEntityBundleInterface || !$bundle_entity->shouldCreateNewRevision()) {
      return;
    }
    $entity->setNewRevision();
    if ($entity instanceof RevisionLogInterface) {
      $entity->setRevisionUserId((int) $this->currentUser()->id());
      $entity->setRevisionCreationTime($this->time->getRequestTime());
      // Do not carry the previous revision's log message forward.
      $entity->setRevisionLogMessage('');
    }
  }

  /**
   * Whether the redirect destination should be recomputed as canonical.
   *
   * The client sends the edited page's path as the destination. When that is
   * the entity's canonical page, saving a changed title can change the
   * autogenerated URL alias, so the canonical URL is recomputed fresh. Any
   * other routed destination is honored as provided: for example the
   * standalone block_content editing surface
   * (daedalus_ui.block_content.edit), where the canonical URL would
   * leave the editing surface.
   *
   * @param string|null $destination
   *   The destination query parameter, if any.
   * @param \Drupal\Core\Entity\EntityInterface $entity
   *   The first saved entity.
   *
   * @return bool
   *   TRUE when the redirect should go to the entity's canonical URL.
   */
  private function shouldRecomputeDestination(?string $destination, EntityInterface $entity): bool {
    if (empty($destination)) {
      return TRUE;
    }
    $url = Url::fromUri('internal:' . $destination);
    if (!$url->isRouted()) {
      // E.g. a stale alias that no longer resolves.
      return TRUE;
    }
    return $url->getRouteName() === "entity.{$entity->getEntityTypeId()}.canonical";
  }

  /**
   * Delete tempstore entities.
   */
  public function delete(Request $request) {
    $this->loopThroughEntities($request, function ($entity) {
      $this->tempstoreRepository->delete($entity);
    });

    return new RedirectResponse($this->getRedirectDestination()->get());
  }

  /**
   * Loop through entities.
   *
   * Gets the relevant entities from the request and loops through them.
   *
   * @param \Symfony\Component\HttpFoundation\Request $request
   *   The current request.
   * @param callable $callable
   *   The function to call.
   *
   * @return \Drupal\Core\Entity\EntityInterface|null
   *   The next from the entity parameter.
   *
   * @throws \Drupal\Component\Plugin\Exception\InvalidPluginDefinitionException
   * @throws \Drupal\Component\Plugin\Exception\PluginNotFoundException
   *
   * @see \Drupal\daedalus_edit\Controller\Tempstore::save()
   * @see \Drupal\daedalus_edit\Controller\Tempstore::delete()
   */
  private function loopThroughEntities(Request $request, callable $callable): ?EntityInterface {
    $parameter = $request->attributes->get('entities');
    if (empty($parameter)) {
      throw new \InvalidArgumentException('No entities to save.');
    }
    $entities = explode('::', $parameter);
    $first_entity = NULL;
    foreach ($entities as $entity) {
      [$entity_type_id, $entity_id] = explode('.', $entity);
      $entity = $this->entityTypeManager()->getStorage($entity_type_id)->load($entity_id);
      Cache::invalidateTags([daedalus_edit_cache_tag($entity)]);
      $callable($entity);
      if (!$first_entity) {
        $first_entity = $entity;
      }
    }
    return $first_entity;
  }

  /**
   * Applies tempstore changes to the original loaded entity.
   *
   * This preserves the entity's original state while applying tempstore
   * modifications, ensuring that $entity->original is set.
   *
   * @param \Drupal\Core\Entity\EntityInterface $tempstore_entity
   *   The entity with tempstore changes.
   * @param \Drupal\Core\Entity\EntityInterface $original_entity
   *   The original loaded entity (with $entity->original set).
   */
  private function applyTempstoreChanges(EntityInterface $tempstore_entity, EntityInterface $original_entity): void {
    // Skip if tempstore entity is the same as original (no changes stored).
    if ($tempstore_entity === $original_entity) {
      return;
    }

    // Transfer all field values from tempstore to original entity.
    foreach ($tempstore_entity->getFields() as $field_name => $field) {
      // Skip fields that don't exist on original entity.
      if (!$original_entity->hasField($field_name)) {
        continue;
      }

      $field_definition = $field->getFieldDefinition();

      if ($field_definition->isComputed()) {
        continue;
      }

      if ($field_definition->isReadOnly()) {
        continue;
      }

      $entity_type = $original_entity->getEntityType();
      $fields_to_ignore = $entity_type->getKeys();
      unset($fields_to_ignore['label']);
      // @todo Consider dispatching an event if it turns out not ignoring fields is a common thing.
      if (in_array($field_name, $fields_to_ignore)) {
        continue;
      }

      $original_entity->set($field_name, $field->getValue());
    }
  }

}
